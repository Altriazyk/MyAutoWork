"""插件可以主动抛的"预期之内的错"。

**为什么要区分。** 插件抛异常有两种完全不同的性质：

- **预期之内的**：条件不成立、参数没填对、目标不在画面上。这些是**流程的一部分**，用户
  天天会碰到，而且多半靠节点的 error 出口处理掉。为它们打一整屏栈是纯噪音 —— 用户看到的
  是"出错了"，实际发生的是"if 走了 false 分支"。
- **真的有 bug**：插件代码写错了。这时完整栈是唯一有用的线索，**一个字都不能省**。

把它们混在一起，要么噪音淹没日志，要么真 bug 被"预期错误"的简洁提示盖掉。所以做成一类
显式的异常：抛它 = "这是正常情况，一行说清楚就行"。

内核侧的处理在 ``kernel/worker.py``：这一类的只往日志写一行，其余照旧打完整栈。
"""

from __future__ import annotations

__all__ = ["ExpectedError", "ConditionNotMet"]


class ExpectedError(RuntimeError):
    """预期之内的失败。日志里只留一行，不打栈；但仍然会走节点的 error 出口。"""


class ConditionNotMet(ExpectedError):
    """条件不成立。

    单独一个类是为了让日志能一眼看出"这是分支没走通"，而不是"某个动作坏了" ——
    条件判断是**每次运行都会走其中一边**的东西，它的"否"不该看起来像故障。
    """
